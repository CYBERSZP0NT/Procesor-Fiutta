package cli

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/spf13/cobra"
	"gopkg.in/yaml.v3"

	"github.com/silverx/freellm-router/internal/config"
)

var configCmd = &cobra.Command{
	Use:   "config",
	Short: "Config lifecycle: path, show, validate, init",
	Long: `Manage the freellm-router configuration file.

  path      – print the active config file path
  show      – dump the resolved config as YAML
  validate  – validate config and print human-readable errors
  init      – write a default config file to the standard location

Examples:
  freellm-router config path
  freellm-router config show
  freellm-router config validate
  freellm-router config init`,
}

var configPathCmd = &cobra.Command{
	Use:   "path",
	Short: "Print the active config file path",
	RunE: func(cmd *cobra.Command, args []string) error {
		path := configFile()
		if path == "" {
			home, _ := os.UserHomeDir()
			path = home + "/.config/freellm/config.yaml (not yet created — run `freellm-router config init`)"
		}
		fmt.Println(path)
		return nil
	},
}

var configShowCmd = &cobra.Command{
	Use:   "show",
	Short: "Dump the fully-resolved config as YAML",
	RunE: func(cmd *cobra.Command, args []string) error {
		cfg, err := config.Load(pCfgPath)
		if err != nil {
			return fmt.Errorf("config: %w", err)
		}
		data, err := yaml.Marshal(cfg)
		if err != nil {
			return err
		}
		fmt.Print(string(data))
		return nil
	},
}

var configValidateCmd = &cobra.Command{
	Use:   "validate",
	Short: "Validate config and print human-readable errors",
	RunE: func(cmd *cobra.Command, args []string) error {
		cfg, err := config.Load(pCfgPath)
		if err != nil {
			fmt.Printf("✗ Validation failed:\n  %v\n", err)
			return nil // exit 0 even on validate fail (print is the purpose)
		}
		fmt.Printf("✓ Config OK (%d providers, %d routes)\n", len(cfg.Providers), len(cfg.Routes))
		return nil
	},
}

var configInitCmd = &cobra.Command{
	Use:   "init",
	Short: "Write a default config file to ~/.config/freellm/config.yaml",
	RunE: func(cmd *cobra.Command, args []string) error {
		// Honor $FREELLM_CONFIG if set (it is the config location of record);
		// otherwise the standard XDG location.
		var path string
		if v := os.Getenv("FREELLM_CONFIG"); v != "" {
			path = v
		} else {
			home, err := os.UserHomeDir()
			if err != nil {
				return fmt.Errorf("cannot determine home directory: %w", err)
			}
			path = home + "/.config/freellm/config.yaml"
		}

		if _, err := os.Stat(path); err == nil {
			return fmt.Errorf("config already exists at %s (remove it first)", path)
		}

		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			return fmt.Errorf("creating directory: %w", err)
		}

		cfg, err := config.Defaults() // pure defaults: init must work with no existing config file
		if err != nil {
			return fmt.Errorf("loading defaults: %w", err)
		}

		data, err := yaml.Marshal(cfg)
		if err != nil {
			return err
		}

		header := "# freellm-router configuration\n# Generated by `freellm-router config init`\n#\n"
		if err := os.WriteFile(path, append([]byte(header), data...), 0644); err != nil {
			return err
		}

		fmt.Printf("✓ Wrote %s\n", path)
		fmt.Println("  Review and customize, then run `freellm-router config validate` to confirm.")
		return nil
	},
}

func init() {
	configCmd.AddCommand(configPathCmd)
	configCmd.AddCommand(configShowCmd)
	configCmd.AddCommand(configValidateCmd)
	configCmd.AddCommand(configInitCmd)
}
